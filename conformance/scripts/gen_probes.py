# Yield/resume (NEP-519) on the async probe: y.yield_create yields
# y.on_yield (no arguments) and stores its data id; the flow's `after`
# steps resume it from a second transaction (y.resume with a 100-byte
# payload, 300 Tgas) or let it time out (expire), each once the chain is
# idle. The callback belongs to the yielding transaction.
RESUME = (Y, "resume", {"bytes": 100})
def yflow(name, about, cb_ggas, cb_weight, after=(), extra=None, **kw):
    a = {"cb_ggas": cb_ggas, "cb_weight": cb_weight}
    a.update(extra or {})
    flow(name, about, Y, "yield_create", a, statics=[(f"{Y}.on_yield", [[cb_ggas, cb_weight]])], after=after, **kw)
