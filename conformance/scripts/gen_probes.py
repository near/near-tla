def call(rx, m, args="", st=0, wt=0, dep=0):
    d = {"method": m, "args": args, "static_ggas": st, "weight": wt}
    if rx: d["receiver"] = rx
    if dep: d["deposit"] = str(dep)
    return d

def tomlmap(d):
    return "{ " + ", ".join(f'"{k}" = "{v}"' for k, v in d.items()) + " }"

def flow(name, about, rx, m, args, dep="", statics=(), path="", path_for=(), signer="alice.near", grid="standard", keys=None, model_keys=None, comment="", after=()):
    s = comment + f'''[[flow]]
name = "{name}"
about = "{about}"
grid = "{grid}"
'''
    if keys:
        s += f"keys = {tomlmap(keys)}\n"
    if model_keys:
        s += f"model_keys = {tomlmap(model_keys)}\n"
    if path:
        s += f'path = "{path}"\n'
        if path_for: s += f"path_for = {json.dumps(list(path_for))}\n"
    a = args if isinstance(args, str) else json.dumps(args)
    s += f'''tx = {{ signer = "{signer}", receiver = "{rx}", method = "{m}", args = '{a}', deposit = "{dep}" }}
'''
    for child, acts in statics:
        s += f'''[[flow.static]]
child = "{child}"
actions = {json.dumps(acts)}
'''
    for a in after:
        if a == "expire":
            s += "[[flow.after]]\nexpire = true\n"
        else:
            arx, am, aargs = a
            s += f'''[[flow.after]]
call = {{ signer = "{signer}", receiver = "{arx}", method = "{am}", args = '{json.dumps(aargs)}' }}
'''
    w(s)

