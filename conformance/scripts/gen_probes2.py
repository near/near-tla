#!/usr/bin/env python3
"""Writes flows/probes2.toml (the flow set probes2: probe2's rule parts, on
z-probe.near). Edit this, then run it: python3 scripts/gen_probes2.py"""
import os
import json
NEAR = 10**24
PK = "ed25519:6E8sCci9badyRkXb3JoRpBj5p8C6Tw41ELDZoiihKEtp"
out = []
w = out.append
w('''# probe2 flows: the rule parts of the second generic probe that a flow can
# observe (the flow set probes2, scripts/flowsets.py; see README.md for the
# format). Its own flows file, so its sweeps (data/probes2) and table
# (tla/CalibProbes2.tla) are apart from flows/probes.toml's.
#
# alice.near signs; z-probe.near runs probe2; p-probe.near and q-probe.near
# the generic probe (p's chain, q's ret and fail as inputs); bob.near is a
# plain account. Model names: alice, bob, p, q, z. Gas in Ggas unless named
# tgas; deposits in yocto. Every account holds 1000 NEAR, as in the model.
#
# Generated by scripts/gen_probes2.py: edit that, not this file.

[world]
names = { "alice.near" = "alice", "bob.near" = "bob", "p-probe.near" = "p", "q-probe.near" = "q", "z-probe.near" = "z" }

[[account]]
id = "alice.near"
near = 1000

[[account]]
id = "bob.near"
near = 1000

[[contract]]
id = "p-probe.near"
wasm = "../probes/res/probe.wasm"
source = "conformance/probes/probe (near-sdk 5.29.1)"

[[contract]]
id = "q-probe.near"
wasm = "../probes/res/probe.wasm"
source = "conformance/probes/probe (near-sdk 5.29.1)"

[[contract]]
id = "z-probe.near"
wasm = "../probes/res/probe2.wasm"
source = "conformance/probes/probe2 (near-sdk 5.29.1)"

# probe2's paths, from its logs: a resume the host accepted or not; a yield
# callback that got a payload or timed out; a yield_id with the marker
# `key = "reuse"` (logged, nothing else: a calibration-key choice, see
# yid_reuse) or not.
[[path_rule]]
call = "z-probe.near.resume"
log = "resume ok"
path = "ok"
else = "none"

[[path_rule]]
call = "z-probe.near.on_yield"
log = "timeout"
path = "timeout"
else = "payload"

[[path_rule]]
call = "z-probe.near.yield_id"
log = "key reuse"
path = "reuse"
else = "new"

# Burn sizes: ret(bytes) by its argument, in KB (1000 bytes).
[[size]]
key = "q-probe.near.ret"
from = "arg:bytes"
div = 1000
''')

def call(rx, m, args="", st=0, wt=0, dep=0):
    d = {"method": m, "args": args if isinstance(args, str) else json.dumps(args), "static_ggas": st, "weight": wt}
    if rx: d["receiver"] = rx
    if dep: d["deposit"] = str(dep)
    return d

def tomlmap(d):
    return "{ " + ", ".join(f'"{k}" = "{v}"' for k, v in d.items()) + " }"

def flow(name, about, rx, m, args, statics=(), path="", path_for=(), signer="alice.near", grid="standard", keys=None, comment="", after=()):
    s = comment + f'''[[flow]]
name = "{name}"
about = "{about}"
grid = "{grid}"
'''
    if keys:
        s += f"keys = {tomlmap(keys)}\n"
    if path:
        s += f'path = "{path}"\n'
        if path_for: s += f"path_for = {json.dumps(list(path_for))}\n"
    a = args if isinstance(args, str) else json.dumps(args)
    s += f'''tx = {{ signer = "{signer}", receiver = "{rx}", method = "{m}", args = '{a}', deposit = "" }}
'''
    for child, acts in statics:
        s += f'''[[flow.static]]
child = "{child}"
actions = {json.dumps(acts)}
'''
    for a in after:
        if a == "expire":
            s += "[[flow.after]]\nexpire = true\n"
        else:
            arx, am, aargs = a
            s += f'''[[flow.after]]
call = {{ signer = "{signer}", receiver = "{arx}", method = "{am}", args = '{json.dumps(aargs)}' }}
'''
    w(s)

P, Q, Z = "p-probe.near", "q-probe.near", "z-probe.near"

# R5: z.refund_call creates z.paid (static 10000 w1) with a 2 NEAR deposit
# from z, which panics, so the deposit is refunded: to the refund_to target
# when set (promise_set_refund_to), else to z, the predecessor. The set
# compares deposit refunds (flowsets.py `refunds`): the refund's receiver
# is in its label.
PAID = call(Z, "paid", {"fail": True}, 10000, 1, 2 * NEAR)
for name, rto in (("refund_to_bob", "bob.near"), ("refund_to_none", None)):
    a = {"c": PAID}
    if rto: a["refund_to"] = rto
    flow(name, f"z.refund_call(z.paid(fail) static 10000 w1 with 2 NEAR, refund_to {rto or 'unset'}): the deposit is refunded to {rto or 'z'}",
         Z, "refund_call", a, statics=[(f"{Z}.paid", [[10000, 1]])], path=name.split("_")[-1], path_for=[f"{Z}.refund_call", f"{Z}.paid"])

# C6, one result by index: z.join joins q.ret(1000), q.ret(2000) and
# q.ret(4000) (static 10000 w0) flat or nested, then z.on_expect(i, len)
# (static 10050 w1), which fails unless result i has len bytes (-1:
# Failed). Nested joins flatten in argument order: "inner" ((k1 & k2) & k0)
# gives k1, k2, k0. The join's path is its nesting. (With a callback
# static of 10000, the sim's leftover at the creator's edge was 2 Ggas,
# below the table's resolution: the exec fees it prepays are rounded up to
# the Ggas, 4 x 0.9; 10050 moves the edge 50 Ggas off a grid point.)
RET = [call(Q, "ret", {"bytes": n}, 10000, 0) for n in (1000, 2000, 4000)]
FAILMID = [RET[0], call(Q, "fail", {"key": "k"}, 10000, 0), RET[2]]
def idx(name, about, kids, nest, i, n):
    cb = call(Z, "on_expect", {"i": i, "len": n}, 10050, 1)
    statics = [(f"{Q}.{m}", [[10000, 0]]) for m in sorted({k["method"] for k in kids})] + [(f"{Z}.on_expect", [[10050, 1]])]
    flow(name, about, Z, "join", {"kids": kids, "nest": nest, "cb": cb}, statics=statics, path=nest, path_for=[f"{Z}.join"])
# Every nesting at every index; the inputs' sizes in flattened order:
ORDER = {"flat": (1000, 2000, 4000), "left": (1000, 2000, 4000), "right": (1000, 2000, 4000), "inner": (2000, 4000, 1000)}
for nest, sizes in ORDER.items():
    for i, n in enumerate(sizes):
        idx(f"idx_{nest}_{i}", f"z.join(q.ret 1000, 2000, 4000 bytes; {nest}), then z.on_expect({i}, {n} bytes)", RET, nest, i, n)
for i, n in enumerate((1000, -1, 4000)):
    idx(f"idx_fail_mid_{i}", f"z.join(q.ret(1000), q.fail, q.ret(4000); flat), then z.on_expect({i}, {'Failed' if n < 0 else f'{n} bytes'})",
        FAILMID, "flat", i, n)

# C7, promise_yield_create_with_id: z.yield_id yields z.on_yield (static
# 5000 w1) under a custom id; the after steps (alice, 300 Tgas) create it
# again, resume it by id (10 bytes) or let it time out. A pending id makes
# a create return u64::MAX and park nothing (no children: the burn key's
# shape "-").
ONY = [(f"{Z}.on_yield", [[5000, 1]])]
def yid(name, about, args, after=(), **kw):
    a = {"cb_ggas": 5000}
    a.update(args)
    flow(name, about, Z, "yield_id", a, statics=ONY, after=after, **kw)
def resume(i, n=10):
    return (Z, "resume", {"id": i, "bytes": n})
yid("yid_twice", "z.yield_id(t) creating t twice in one call: the second is a duplicate; then the yield times out", {"id": "t", "twice": True}, ["expire"],
    path="twice", path_for=[f"{Z}.yield_id"])
yid("yid_dup_later", "z.yield_id(d), then z.yield_id(d) again (a duplicate: nothing parked), then z.resume(d)", {"id": "d"},
    [(Z, "yield_id", {"id": "d", "cb_ggas": 5000}), resume("d")])
# yid_reuse: a create of an id used before burns about 17 Ggas more than a
# first one (the runtime has written and removed the id's mapping), so the
# second create carries the marker key = "reuse", which probe2 only logs:
# its own burn key (path "reuse"), a calibration-key choice, not semantics.
yid("yid_reuse", "z.yield_id(r), z.resume(r) (its callback runs), then z.yield_id(r) again: a new yield, which times out", {"id": "r"},
    [resume("r"), (Z, "yield_id", {"id": "r", "cb_ggas": 5000, "key": "reuse"}), "expire"])
yid("yid_again", "z.yield_id(a) whose callback re-creates a (static 5000 w1); z.resume(a) twice: each callback runs", {"id": "a", "again": True},
    [resume("a"), resume("a")])
flow("yid_resume_none", "z.resume(n) with no yield of that id: the host returns false (the resume path none)", Z, "resume",
     {"id": "n", "bytes": 10})
yid("yid_deposit", "z.yield_id(p) with a 2 NEAR deposit from z, then z.resume(p): the callback receives it", {"id": "p", "deposit": str(2 * NEAR)},
    [resume("p")], path="dep", path_for=[f"{Z}.yield_id"])
yid("yid_deposit_over", "z.yield_id(o) with a 2000 NEAR deposit, more than z holds: the call fails", {"id": "o", "deposit": str(2000 * NEAR)},
    path="over", path_for=[f"{Z}.yield_id"])

# C7, a returned yield: p.chain(z.yield_id(ret) static 30000 w1, then
# z.on_expect(0, len) static 10000 w1). z.yield_id makes a plain yield
# (promise_yield_create, its data id stored) and returns it, so p's
# callback waits for the yield callback and reads its result: the resume's
# payload, or, on a timeout, an empty value (on_yield returns nothing).
def yret(name, about, n, after):
    kid = call(Z, "yield_id", {"cb_ggas": 5000, "ret": True}, 30000, 1)
    cb = call(Z, "on_expect", {"i": 0, "len": n}, 10000, 1)
    flow(name, about, P, "chain", {"kids": [kid], "cb": cb}, keys={"chain": "chain/on_expect,yield_id"},
         statics=[(f"{Z}.yield_id", [[30000, 1]]), (f"{Z}.on_expect", [[10000, 1]])] + ONY,
         path="ret", path_for=[f"{Z}.yield_id"], after=after)
yret("yret_resume", "p.chain(z.yield_id returned), then z.resume(1000 bytes): p's callback reads the 1000-byte payload", 1000,
     [(Z, "resume", {"bytes": 1000})])
yret("yret_timeout", "p.chain(z.yield_id returned), then the yield times out: p's callback reads an empty success", 0, ["expire"])

# B1: z.stake_then stakes z (10 NEAR, or 2000 NEAR, more than z holds:
# TriesToStake), then z.on_expect(0, len) (static 10000 w1) on the Stake's
# result: empty bytes on success, Failed on failure.
for name, amt, n in (("stake_ok", 10, 0), ("stake_too_much", 2000, -1)):
    flow(name, f"z.stake_then({amt} NEAR), then z.on_expect(0, {'empty' if n == 0 else 'Failed'})", Z, "stake_then",
         {"amount": str(amt * NEAR), "pk": PK, "cb_ggas": 10000, "expect": n}, statics=[(f"{Z}.on_expect", [[10000, 1]])])
open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "flows", "probes2.toml"), "w").write("\n".join(out))
