#!/usr/bin/env python3
"""Writes flows/mt.toml, the flow set `mt`: NEP-245 on the `mt` probe
(near-sdk-contract-tools 4.0.0) with the `mtrecv` receiver, for the
conformance comparison and the multi-token gas table (MtConf.tla,
CalibMt.tla; modules/CalibMtStd.tla).

  python3 scripts/gen_mt.py        (from conformance/)
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MT, RX = "mt-probe.near", "mr-probe.near"
IDS = ["t1", "t2", "t3"]

HEAD = f'''# The flow set `mt` (scripts/flowsets.py): NEP-245 on the `mt` probe, a plain
# near-sdk-contract-tools 4.0.0 multi token, and the `mtrecv` receiver, whose
# mt_on_transfer answers as its msg says. The conformance sweeps and the
# calibration of the multi-token burn keys (see README.md for the format).
#
# alice.near holds 1000 of each of t1, t2, t3 and signs; dave.near is a plain
# account. Model names: alice, dave, mt, mr. Gas in Ggas unless named tgas;
# deposits in yocto.
#
# Generated by scripts/gen_mt.py: edit that, not this file.

[world]
names = {{ "alice.near" = "alice", "dave.near" = "dave", "{MT}" = "mt", "{RX}" = "mr" }}

[[account]]
id = "alice.near"
near = 100000

[[account]]
id = "dave.near"
near = 1000

[[contract]]
id = "{MT}"
wasm = "../probes/res/mt.wasm"
source = "conformance/probes/mt (near-sdk-contract-tools 4.0.0, near-sdk 5.29.1)"
init = {{ method = "new", args = '{{"owner_id": "alice.near", "token_ids": ["t1", "t2", "t3"], "supply": "1000"}}' }}

[[contract]]
id = "{RX}"
wasm = "../probes/res/mtrecv.wasm"
source = "conformance/probes/mtrecv (near-sdk 5.29.1)"

# near-sdk-contract-tools 4.0.0 (src/standard/nep245/mod.rs:264-287):
# mt_on_transfer gets static 0 and weight 10, mt_resolve_transfer static
# 5 Tgas (GAS_FOR_MT_RESOLVE_TRANSFER) and weight 1, for any number of ids.
[[static]]
child = "{RX}.mt_on_transfer"
actions = [[0, 10]]

[[static]]
child = "{MT}.mt_resolve_transfer"
actions = [[5000, 1]]

# Burns per id: the batch methods, the resolver and the receiver grow with
# the number of token ids.
'''


def size(key):
    return f'[[size]]\nkey = "{key}"\nfrom = "arg_count:token_ids"\n\n'


# No refund/norefund path rule for the resolver: its burn grows with the
# number of ids, and a merged account's path keys are constant, so the
# method key's line (base + per * ids) covers both paths, from above.


def tx(method, args, deposit="1"):
    a = json.dumps(args).replace("'", "\\'")
    return f'{{ signer = "alice.near", receiver = "{MT}", method = "{method}", args = \'{a}\', deposit = "{deposit}" }}'


def flow(name, about, t, grid="standard", path=None, path_for=None):
    s = f'[[flow]]\nname = "{name}"\nabout = "{about}"\ngrid = "{grid}"\n'
    if path:
        s += f'path = "{path}"\n'
        s += "path_for = [" + ", ".join(f'"{p}"' for p in path_for) + "]\n"
    return s + f"tx = {t}\n\n"


def main():
    out = [HEAD]
    for k in (f"{MT}.mt_batch_transfer", f"{MT}.mt_batch_transfer_call", f"{MT}.mt_resolve_transfer",
              f"{RX}.mt_on_transfer"):
        out.append(size(k))
    on = [f"{RX}.mt_on_transfer"]
    # plain transfers
    out.append(flow("mt_xfer", "mt.mt_transfer(dave, t1, 1)",
                    tx("mt_transfer", {"receiver_id": "dave.near", "token_id": "t1", "amount": "1"})))
    for n in (1, 2, 3):
        ids, amts = IDS[:n], [str(i + 1) for i in range(n)]
        out.append(flow(f"mt_bxfer{n}", f"mt.mt_batch_transfer(dave, {ids}, {amts})",
                        tx("mt_batch_transfer", {"receiver_id": "dave.near", "token_ids": ids, "amounts": amts})))
    # single-id transfer_call
    for msg in ("keep", "return"):
        out.append(flow(f"mt_call_{msg}", f"mt.mt_transfer_call(mr, t1, 10, msg={msg})",
                        tx("mt_transfer_call", {"receiver_id": RX, "token_id": "t1", "amount": "10", "msg": msg}),
                        path=msg, path_for=on))
    # batch transfer_call: every receiver answer on two ids, keep and return on one and three
    cases = [(2, m) for m in ("keep", "return", "over", "short", "long", "mal", "empty", "panic", "burn:20000")]
    cases += [(1, "keep"), (1, "return"), (3, "keep"), (3, "return")]
    for n, msg in cases:
        ids, amts = IDS[:n], [str(10 * (i + 1)) for i in range(n)]
        tag = msg.replace(":", "")
        out.append(flow(f"mt_bcall{n}_{tag}", f"mt.mt_batch_transfer_call(mr, {ids}, {amts}, msg={msg})",
                        tx("mt_batch_transfer_call", {"receiver_id": RX, "token_ids": ids, "amounts": amts, "msg": msg}),
                        path=tag, path_for=on))
    # Below 30 Tgas the _call methods panic (the floor); every flow above shows
    # it: their burn up to the panic (0.33 Tgas) is under the grid's 0.5 Tgas,
    # so they never run out of gas first.
    with open(os.path.join(HERE, "flows", "mt.toml"), "w") as f:
        f.write("".join(out).rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
